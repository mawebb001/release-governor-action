#!/usr/bin/env node
/**
 * Cursor hook: sessionStart — license gate, telemetry flush, and optional
 * orchestration session init. Everything here is best-effort and silent on
 * success: an offline machine, a broken server, or missing files must never
 * break the session (the hook always exits 0).
 *
 * LICENSE GATE (warn-7 / disable-14 / instant-restore): this standalone script
 * cannot import the CLI package, so it MIRRORS the pure decision logic in
 * packages/cli/src/license-gate.ts — keep thresholds and decisions in sync
 * (24h revalidation window; explicit KEY_INVALID/KEY_EXPIRED enforces now;
 * otherwise offline grace: <7d silent, 7-13d warn, >=14d enforce).
 *
 * TELEMETRY TRANSPORT IS SHARED with packages/cli/src/flush-journal.ts and
 * packages/orchestrator/src/state-machine.ts: the v2 claim journal
 * (~/.enterprise-skills/.telemetry-journal.jsonl, one JSON object per line,
 * CROSS_PROCESS_FLUSH_DESIGN §3.2). This flusher MIRRORS flush-journal.ts the
 * same way the license gate mirrors license-gate.ts: flushers serialize on an
 * exclusive-create LOCK file (rename is NOT an exclusivity primitive on
 * Windows — ES-P0-JOURNAL-WINDOWS-EXACTLY-ONCE), the journal is claimed by
 * rename ONLY under that lock, POST in batches of 50, append what could not
 * cross BACK to the live journal (never overwrite — D-3), sweep orphaned
 * claims older than 15 minutes only when their owner process is gone (or the
 * hard pid-recycling bound passes), and drain a v1 array file left by old
 * writers (D-4). The 200 cap is enforced here at claim time (§3.3). A claim
 * whose restore fails is LEFT for the sweep, never unlinked.
 */
