function log(msg) {
  try {
    const dir = join(cwd, '.project-ai', 'hook-logs');
    mkdirSync(dir, { recursive: true });
    appendFileSync(join(dir, 'session-start.log'), `[${new Date().toISOString()}] ${msg}\n`);
  } catch {
    /* ignore */
  }
}

function drainStdin() {
  try {
    if (!process.stdin.isTTY) {
      readFileSync(0, 'utf8');
    }
  } catch {
    /* ignore */
  }
}

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------------------
// License gate (warn-7 / disable-14 / instant-restore)
